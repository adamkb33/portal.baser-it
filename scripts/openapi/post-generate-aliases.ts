import { resolve } from 'node:path';

type ServiceAliasConfig = {
  service: 'base' | 'booking' | 'notification' | 'timesheet';
  runtimeExport: 'Base' | 'Booking' | 'Notification' | 'Timesheet';
  runtimeLocal: string;
  aliases: string[];
};

